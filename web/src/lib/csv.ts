export function csvEscapeCell(value: string | number | boolean): string {
  const text = String(value);
  if (/[",\n\r]/.test(text)) {
    return `"${text.replace(/"/g, '""')}"`;
  }
  return text;
}

/** Parse a single CSV record line (RFC 4180-style, no multiline cells). */
export function parseCsvLine(line: string): string[] {
  const cells: string[] = [];
  let current = '';
  let inQuotes = false;
  for (let i = 0; i < line.length; i++) {
    const ch = line[i];
    if (inQuotes) {
      if (ch === '"') {
        if (line[i + 1] === '"') {
          current += '"';
          i++;
        } else {
          inQuotes = false;
        }
      } else {
        current += ch;
      }
    } else if (ch === '"') {
      inQuotes = true;
    } else if (ch === ',') {
      cells.push(current);
      current = '';
    } else {
      current += ch;
    }
  }
  cells.push(current);
  return cells;
}

export function rowsToCsv(headers: string[], rows: (string | number | boolean)[][]): string {
  const lines = [headers.map(csvEscapeCell).join(',')];
  for (const row of rows) {
    lines.push(row.map(csvEscapeCell).join(','));
  }
  return `${lines.join('\n')}\n`;
}
